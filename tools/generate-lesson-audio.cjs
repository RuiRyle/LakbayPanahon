#!/usr/bin/env node
// Local batch job only. Never put the ElevenLabs key in browser code or files.
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const {normalize,readingParts}=require('../js/lesson-narration-text.js');
const preview=require('../js/story-playground-content.js');
const root=path.resolve(__dirname,'..');
const output=path.join(root,'assets/audio/bayani/generated');
const manifestPath=path.join(root,'data/bayani-generated-clips.json');
const scriptPath=path.join(root,'js/bayani-generated-clips.js');
const hash=value=>crypto.createHash('sha256').update(value).digest('hex').slice(0,24);
function jobsFromScenes(scenes){
    const jobs=[];
    for(const scene of scenes){
        if(scene.status!=='active'||typeof scene.content!=='string')continue;
        readingParts(scene.content).forEach((text,index)=>jobs.push({text,reference:`${scene.missionId||'mission'}/${scene.id||'scene'}/part-${index+1}`}));
    }
    return jobs;
}
function previewJobs(){
    const jobs=[];
    for(let step=0;step<5;step++){
        const states=step===1?[null,...preview.clues.map(clue=>clue.id)]:[null];
        for(const activeClue of states){
            preview.narrationParts(step,{activeClue}).forEach((text,index)=>jobs.push({text,reference:`preview/step-${step+1}/${activeClue||'default'}/part-${index+1}`}));
        }
    }
    return jobs;
}
function deduplicate(jobs){
    const unique=new Map();
    for(const job of jobs){const text=normalize(job.text);if(!text)continue;
        if(!unique.has(text))unique.set(text,{text,references:[]});unique.get(text).references.push(job.reference);
    }
    return [...unique.values()];
}
function profileFor(voiceId,modelId){return hash(JSON.stringify({voiceId,modelId,format:'mp3_44100_128'}));}
function filenameFor(text,profile){return hash(profile+'\n'+normalize(text))+'.mp3';}
function isMp3(bytes){return bytes.length>100&&(bytes.subarray(0,3).toString()==='ID3'||(bytes[0]===255&&(bytes[1]&224)===224));}
function atomicWrite(file,content){
    fs.mkdirSync(path.dirname(file),{recursive:true});const temporary=file+'.tmp-'+process.pid;
    try{fs.writeFileSync(temporary,content,{flag:'wx'});fs.renameSync(temporary,file);}finally{if(fs.existsSync(temporary))fs.unlinkSync(temporary);}
}
function publishedEntries(){if(!fs.existsSync(manifestPath))return [];const value=JSON.parse(fs.readFileSync(manifestPath,'utf8'));if(!Array.isArray(value))throw Error('Generated clip manifest is not an array.');return value;}
function publish(entries){
    const json=JSON.stringify(entries,null,2);
    atomicWrite(manifestPath,json+'\n');
    const publicEntries=entries.map(({text,src})=>({text,src}));
    atomicWrite(scriptPath,'// Generated by tools/generate-lesson-audio.cjs. No API credentials.\nwindow.LakbayBayaniVoiceClips = window.LakbayBayaniVoiceClips || [];\nwindow.LakbayBayaniVoiceClips.push(...'+JSON.stringify(publicEntries).replace(/</g,'\\u003c')+');\n');
}
async function providerError(response,apiKey=''){
    let payload;try{payload=await response.json();}catch{}
    const detail=payload?.detail;
    const clean=value=>{
        let text=typeof value==='string'?value:'';
        if(apiKey)text=text.split(apiKey).join('[redacted]');
        return text.replace(/\bsk_[a-zA-Z0-9_-]+/g,'[redacted]').replace(/Bearer\s+[^\s"']+/gi,'Bearer [redacted]').replace(/[\x00-\x1f\x7f]/g,' ').replace(/\s+/g,' ').trim().slice(0,800);
    };
    const status=clean(detail?.status||payload?.error?.code);
    const message=clean(typeof detail==='string'?detail:detail?.message||payload?.error?.message||payload?.message);
    const validation=Array.isArray(detail)?detail.map(item=>clean(item?.msg)).filter(Boolean).join('; '):'';
    const explanation=[status,message||validation].filter(Boolean).join(': ');
    const requestId=clean(response.headers.get('request-id')||response.headers.get('x-request-id'));
    const error=new Error(`ElevenLabs returned HTTP ${response.status}${explanation?' — '+explanation:'. No structured error detail was returned.'}${requestId?' (request '+requestId+')':''}. Completed files are kept; no automatic retry was sent.`);
    error.providerStatus=status;return error;
}
async function checkConnection(config,{request=fetch}={}){
    async function get(endpoint){
        const response=await request('https://api.elevenlabs.io/v1/'+endpoint,{method:'GET',headers:{'xi-api-key':config.apiKey},signal:AbortSignal.timeout(30000)});
        if(!response.ok)throw await providerError(response,config.apiKey);return response.json();
    }
    const voice=await get('voices/'+encodeURIComponent(config.voiceId));
    const models=await get('models');
    if(!Array.isArray(models))throw Error('ElevenLabs returned an unexpected model list.');
    const selected=models.find(model=>model.model_id===config.modelId);
    return {
        voiceAccessible:true,
        selectedModel:config.modelId,
        selectedModelListed:Boolean(selected),
        selectedModelSupportsSpeech:selected?.can_do_text_to_speech===true,
        voiceRecommendedModels:Array.isArray(voice.high_quality_base_model_ids)?voice.high_quality_base_model_ids.filter(id=>typeof id==='string'):[],
        speechModels:models.filter(model=>model.can_do_text_to_speech===true).map(model=>model.model_id),
        note:'Read-only metadata check. No speech was generated. Account credits and successful speech generation are not verified by this check.'
    };
}
async function generate(jobs,config,{request=fetch,folder=output,onClip=()=>{}}={}){
    const result=[];let requests=0,characters=0;
    for(const job of jobs){
        const filename=filenameFor(job.text,config.profile),file=path.join(folder,filename);
        let cached=fs.existsSync(file)&&isMp3(fs.readFileSync(file));
        if(!cached){
            if(requests>=config.limit||characters+job.text.length>config.maxCharacters)continue;
            // A failed/uncertain request is not automatically retried, to avoid duplicate charges.
            const response=await request('https://api.elevenlabs.io/v1/text-to-speech/'+encodeURIComponent(config.voiceId)+'?output_format=mp3_44100_128',{
                method:'POST',headers:{'xi-api-key':config.apiKey,'Content-Type':'application/json',Accept:'audio/mpeg'},
                body:JSON.stringify({text:job.text,model_id:config.modelId}),signal:AbortSignal.timeout(90000)
            });
            if(!response.ok)throw await providerError(response,config.apiKey);
            const mime=response.headers.get('content-type')||'';
            if(!mime.startsWith('audio/'))throw Error('ElevenLabs did not return audio; no clip was installed.');
            const bytes=Buffer.from(await response.arrayBuffer());
            if(!isMp3(bytes))throw Error('The response is not a valid MP3 header; no clip was installed.');
            atomicWrite(file,bytes);requests++;characters+=job.text.length;
        }
        const entry={text:job.text,src:'../assets/audio/bayani/generated/'+filename,profile:config.profile};result.push(entry);onClip(entry,{cached});
    }
    return {entries:result,requests,characters};
}
function decode(value){
    if('stringValue'in value)return value.stringValue;
    if('booleanValue'in value)return value.booleanValue;
    if('integerValue'in value)return Number(value.integerValue);
    if('doubleValue'in value)return value.doubleValue;
    if('nullValue'in value)return null;
    if(value.arrayValue)return(value.arrayValue.values||[]).map(decode);
    if(value.mapValue)return Object.fromEntries(Object.entries(value.mapValue.fields||{}).map(([k,v])=>[k,decode(v)]));
    return undefined;
}
async function firestoreScenes(){
    const project=JSON.parse(fs.readFileSync(path.join(root,'.firebaserc'),'utf8')).projects.default;
    if(!project||process.env.FIRESTORE_EMULATOR_HOST)throw Error('Use the configured project without a Firestore emulator for the published lesson plan.');
    let auth;
    try{auth=require(path.join(process.env.APPDATA||'','npm/node_modules/firebase-tools/lib/auth.js'));}catch{throw Error('Install/log in to Firebase CLI first, or use --source with an exported scene JSON file.');}
    const account=auth.getProjectDefaultAccount(root);if(!account)throw Error('Run firebase login first.');
    const token=await auth.getAccessToken(account.tokens.refresh_token,['https://www.googleapis.com/auth/cloud-platform']);
    const scenes=[];let pageToken='';
    do{
        const url=new URL('https://firestore.googleapis.com/v1/projects/'+encodeURIComponent(project)+'/databases/(default)/documents/storyScenes');
        url.searchParams.set('pageSize','300');if(pageToken)url.searchParams.set('pageToken',pageToken);
        const response=await fetch(url,{headers:{Authorization:'Bearer '+token.access_token},signal:AbortSignal.timeout(30000)});
        if(!response.ok)throw Error('Cannot read storyScenes (HTTP '+response.status+'). No Firestore data was changed.');
        const data=await response.json();
        for(const document of data.documents||[]){const values=Object.fromEntries(Object.entries(document.fields||{}).map(([k,v])=>[k,decode(v)]));scenes.push({id:document.name.split('/').pop(),...values});}
        pageToken=data.nextPageToken||'';
    }while(pageToken);
    return {project,scenes};
}
function parseArgs(argv){
    const options={preview:false,generate:false,plan:false,check:false,source:null,mission:null,limit:1,maxCharacters:5000,help:false};
    const takesValue={'--source':'source','--mission':'mission','--limit':'limit','--max-characters':'maxCharacters'};
    for(let i=0;i<argv.length;i++){
        const arg=argv[i];
        if(arg==='--preview')options.preview=true;
        else if(arg==='--generate')options.generate=true;
        else if(arg==='--plan')options.plan=true;
        else if(arg==='--check')options.check=true;
        else if(arg==='--help'||arg==='-h')options.help=true;
        else if(takesValue[arg]){if(!argv[i+1]||argv[i+1].startsWith('--'))throw Error('Missing value for '+arg);options[takesValue[arg]]=argv[++i];}
        else throw Error('Unknown argument: '+arg);
    }
    for(const key of ['limit','maxCharacters']){options[key]=Number(options[key]);if(!Number.isSafeInteger(options[key])||options[key]<1)throw Error(key+' must be a positive integer.');}
    if(options.plan&&options.generate)throw Error('Choose --plan or --generate, not both.');
    if(options.check&&options.generate)throw Error('--check does not generate audio; run --generate separately.');
    if(!options.help&&!options.check&&!options.preview&&!options.source)throw Error('Choose --preview and/or --source firestore (or a scene JSON file), or use --check.');
    return options;
}
async function main(argv=process.argv.slice(2)){
    const options=parseArgs(argv);
    if(options.help){console.log('Read-only provider check: node tools/generate-lesson-audio.cjs --check\nPlan (no ElevenLabs requests): node tools/generate-lesson-audio.cjs --preview --plan\nAll active mission readings: add --source firestore\nGenerate with environment credentials: add --generate --limit 1\nOptional: --mission ID --max-characters 5000\nJSON source: --source export.json (array of scenes or {scenes:[...]}).');return;}
    const voiceId=(process.env.ELEVENLABS_VOICE_ID||'').trim(),modelId=(process.env.ELEVENLABS_MODEL_ID||'eleven_multilingual_v2').trim();
    if(voiceId&&!/^[a-zA-Z0-9_-]{1,128}$/.test(voiceId))throw Error('ELEVENLABS_VOICE_ID has an invalid format.');
    if(!/^[a-zA-Z0-9_-]{1,128}$/.test(modelId))throw Error('ELEVENLABS_MODEL_ID has an invalid format.');
    if(options.check){
        if(!voiceId||!process.env.ELEVENLABS_API_KEY)throw Error('Set ELEVENLABS_VOICE_ID and ELEVENLABS_API_KEY in this same terminal before --check.');
        console.log(JSON.stringify(await checkConnection({voiceId,modelId,apiKey:process.env.ELEVENLABS_API_KEY}),null,2));return;
    }
    let scenes=[],project=null;
    if(options.source==='firestore')({scenes,project}=await firestoreScenes());
    else if(options.source){const value=JSON.parse(fs.readFileSync(path.resolve(root,options.source),'utf8'));scenes=Array.isArray(value)?value:value.scenes;if(!Array.isArray(scenes))throw Error('Source JSON needs an array of scenes or a scenes array.');}
    if(options.mission)scenes=scenes.filter(scene=>scene.missionId===options.mission);
    const jobs=deduplicate([...(options.preview?previewJobs():[]),...jobsFromScenes(scenes)]);
    const profile=profileFor(voiceId,modelId),pending=jobs.filter(job=>{
        if(!voiceId)return true;const file=path.join(output,filenameFor(job.text,profile));return!fs.existsSync(file)||!isMp3(fs.readFileSync(file));
    });
    const summary={mode:options.generate?'generate':'plan',project,activeScenes:scenes.filter(scene=>scene.status==='active').length,uniqueClips:jobs.length,characters:jobs.reduce((n,job)=>n+job.text.length,0),pendingClips:pending.length,pendingCharacters:pending.reduce((n,job)=>n+job.text.length,0),voiceConfigured:Boolean(voiceId),model:modelId};
    atomicWrite(path.join(root,'build/bayani-narration/plan.json'),JSON.stringify({summary,jobs},null,2)+'\n');console.log(JSON.stringify(summary,null,2));
    if(!options.generate){console.log('No ElevenLabs requests made. Review build/bayani-narration/plan.json.');return;}
    if(!voiceId||!process.env.ELEVENLABS_API_KEY)throw Error('Set ELEVENLABS_VOICE_ID and ELEVENLABS_API_KEY in this terminal first. Do not put the key in project files.');
    const entries=new Map(publishedEntries().filter(entry=>entry.profile===profile).map(entry=>[normalize(entry.text),entry]));
    let completed=0;
    const result=await generate(jobs,{voiceId,modelId,profile,apiKey:process.env.ELEVENLABS_API_KEY,limit:options.limit,maxCharacters:options.maxCharacters},{onClip:(entry,{cached})=>{
        entries.set(normalize(entry.text),entry);
        if(!cached){publish([...entries.values()]);console.log('Saved new clip '+(++completed)+': '+path.basename(entry.src));}
    }});
    publish([...entries.values()]);
    console.log(JSON.stringify({generated:result.requests,generatedCharacters:result.characters,availableForThisPlan:result.entries.length,remaining:jobs.length-result.entries.length,limits:{clips:options.limit,characters:options.maxCharacters}},null,2));
    console.log('Generated clips are connected locally. Refresh the lesson. Re-run to resume with the same voice/model.');
}
module.exports={jobsFromScenes,previewJobs,deduplicate,profileFor,filenameFor,isMp3,generate,parseArgs,providerError,checkConnection};
if(require.main===module)main().catch(error=>{console.error(error.name==='TimeoutError'?'Request timed out. No automatic retry was sent. Check the provider history before retrying.':error.message);process.exitCode=1;});
